package srtp

import (
	"crypto/aes"
	"encoding/binary"
)

// maxKeyDerivationRateIndex is the maximum value of r = index DIV kdr that can be
// encoded in the 48-bit (six-octet) "index DIV kdr" field of the key derivation
// input block, see RFC 3711 section 4.3.1.
const maxKeyDerivationRateIndex = uint64(1<<48) - 1

// aesCmKeyDerivation implements the AES-CM based PRF key derivation from
// RFC 3711 section 4.3.
//
// indexOverKdr is r = packet index DIV key_derivation_rate, encoded as a
// 48-bit unsigned integer (see RFC 3711 section 4.3.1 and Appendix B.3).
// With the convention "a DIV 0 = 0", a zero key derivation rate always
// uses indexOverKdr == 0, so the initial session keys stay valid for the
// whole lifetime of the master key.
func aesCmKeyDerivation(label byte, masterKey, masterSalt []byte, indexOverKdr uint64, outLen int) ([]byte, error) {
	// https://tools.ietf.org/html/rfc3711#appendix-B.3
	// The input block for AES-CM is generated by exclusive-oring the master salt with the
	// concatenation of the encryption key label with (index DIV kdr).
	//
	// Layout of the 14-octet master salt / key_id area inside the 16-octet PRF input:
	//   octets 0..6: master salt
	//   octet 7:     key label (key_id's most significant octet)
	//   octets 8..13: r = index DIV kdr, six octets, big-endian (right-aligned key_id)
	// The two trailing octets stay zero, implementing the (x * 2^16) IV scaling
	// from RFC 3711 section 4.3.3; they are overwritten with the AES-CM block counter.

	nMasterSalt := len(masterSalt)

	prfIn := make([]byte, 16)
	copy(prfIn[:nMasterSalt], masterSalt)

	prfIn[7] ^= label

	// RFC 3711 section 4.3.1: r is treated as a bit string of the same length as
	// the packet index. The SRTP index is 48 bits and the SRTCP index (0 || SRTCP
	// index) is at most 32 bits, so any valid r fits into six octets. A value that
	// does not fit cannot be encoded and must be rejected by the caller.
	prfIn[8] ^= byte(indexOverKdr >> 40)
	prfIn[9] ^= byte(indexOverKdr >> 32)
	prfIn[10] ^= byte(indexOverKdr >> 24)
	prfIn[11] ^= byte(indexOverKdr >> 16)
	prfIn[12] ^= byte(indexOverKdr >> 8)
	prfIn[13] ^= byte(indexOverKdr)

	// The resulting value is then AES encrypted using the master key to get the cipher key.
	block, err := aes.NewCipher(masterKey)
	if err != nil {
		return nil, err
	}

	nBlockSize := block.BlockSize()
	out := make([]byte, ((outLen+nBlockSize-1)/nBlockSize)*nBlockSize)
	var i uint16
	for n := 0; n < outLen; n += nBlockSize {
		binary.BigEndian.PutUint16(prfIn[len(prfIn)-2:], i)
		block.Encrypt(out[n:n+nBlockSize], prfIn)
		i++
	}

	return out[:outLen], nil
}

// Generate IV https://tools.ietf.org/html/rfc3711#section-4.1.1
// where the 128-bit integer value IV SHALL be defined by the SSRC, the
// SRTP packet index i, and the SRTP session salting key k_s, as below.
// - ROC = a 32-bit unsigned rollover counter (ROC), which records how many
// -       times the 16-bit RTP sequence number has been reset to zero after
// -       passing through 65,535
// i = 2^16 * ROC + SEQ
// IV = (salt*2 ^ 16) | (ssrc*2 ^ 64) | (i*2 ^ 16).
func generateCounter(
	sequenceNumber uint16,
	rolloverCounter uint32,
	ssrc uint32, sessionSalt []byte,
) (counter [16]byte) {
	copy(counter[:], sessionSalt)

	counter[4] ^= byte(ssrc >> 24)
	counter[5] ^= byte(ssrc >> 16) //nolint:gosec
	counter[6] ^= byte(ssrc >> 8)  //nolint:gosec
	counter[7] ^= byte(ssrc)       //nolint:gosec
	counter[8] ^= byte(rolloverCounter >> 24)
	counter[9] ^= byte(rolloverCounter >> 16) //nolint:gosec
	counter[10] ^= byte(rolloverCounter >> 8) //nolint:gosec
	counter[11] ^= byte(rolloverCounter)      //nolint:gosec
	counter[12] ^= byte(sequenceNumber >> 8)
	counter[13] ^= byte(sequenceNumber) //nolint:gosec

	return counter
}
